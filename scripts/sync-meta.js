#!/usr/bin/env node
/* Bakes <title>, description, Open Graph and Twitter tags from config.js into index.html
   so link previews (Discord, Slack, X, Facebook…) work. Run: npm run meta */
const fs = require('fs'), path = require('path');
global.window = {}; require(path.join(__dirname, '..', 'config.js'));
const S = window.SITE.site, lang = S.language || 'en';
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const abs = (p) => /^https?:/i.test(p) ? p : S.url.replace(/\/$/, '') + '/' + p.replace(/^\.?\//, '');
const type = (p) => /\.svg$/i.test(p) ? 'image/svg+xml' : /\.png$/i.test(p) ? 'image/png' : /\.webp$/i.test(p) ? 'image/webp' : 'image/jpeg';
const lines = [
  `<title>${esc(S.title)}</title>`,
  `<meta name="description" content="${esc(S.description)}" />`,
  `<meta name="theme-color" content="${esc(S.themeColor || '#0b0d12')}" />`,
  `<link rel="canonical" href="${esc(S.url)}" />`,
  `<link rel="icon" type="${type(S.favicon)}" href="${esc(S.favicon)}" />`,
  `<meta property="og:type" content="website" />`,
  `<meta property="og:url" content="${esc(S.url)}" />`,
  `<meta property="og:title" content="${esc(S.title)}" />`,
  `<meta property="og:description" content="${esc(S.description)}" />`,
  `<meta property="og:image" content="${esc(abs(S.shareImage))}" />`,
  `<meta property="og:image:width" content="1200" />`,
  `<meta property="og:image:height" content="630" />`,
  `<meta name="twitter:card" content="summary_large_image" />`,
  `<meta name="twitter:title" content="${esc(S.title)}" />`,
  `<meta name="twitter:description" content="${esc(S.description)}" />`,
  `<meta name="twitter:image" content="${esc(abs(S.shareImage))}" />`,
].map((l) => '  ' + l).join('\n');
const file = path.join(__dirname, '..', 'index.html');
let html = fs.readFileSync(file, 'utf8');
html = html.replace(/<!-- META:START[\s\S]*?-->[\s\S]*?<!-- META:END -->/, `<!-- META:START (auto-generated by \`npm run meta\` from config.js — safe to leave as is) -->\n${lines}\n  <!-- META:END -->`)
           .replace(/<html lang="[^"]*"/, `<html lang="${lang}"`);
fs.writeFileSync(file, html);
console.log('✔ index.html meta tags synced from config.js');
